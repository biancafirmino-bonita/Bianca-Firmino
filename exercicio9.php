<?php

$n1 = 104;
$n2 = 15;
$operacao = "*";

if($operacao == "+"){
    echo "A soma: ", $n1 + $n2;
}
elseif($operacao == "-"){
    echo "A subtracao: ", $n1 - $n2;
}
elseif($operacao == "*"){
    echo "A multiplicacao: ", $n1 * $n2;
}
elseif($operacao == "/"){
    echo "A divisao: ", $n1 / $n2;
}